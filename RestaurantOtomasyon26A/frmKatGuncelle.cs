        private void kategoridoldur()
        {
            var kategori = db.TBLKATEGORI.Find(secilenId);
            if (kategori != null)
            {
                tBadsoyad.Text = kategori.KATEGORI;
                if (kategori.DURUM == true)
                {
                    radioButton1.Checked = true;
                }
                else
                {
                    radioButton2.Checked = true;
                }
            }
            else
            {
                MessageBox.Show("Kategori bulunamadı!");
                this.Close();
            }
        }

        private void frmKatGuncelle_Load(object sender, EventArgs e)
        {
            kategoridoldur();
        }
